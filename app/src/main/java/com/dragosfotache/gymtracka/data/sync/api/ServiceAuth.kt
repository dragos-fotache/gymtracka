package com.dragosfotache.gymtracka.data.sync.api

import com.dragosfotache.gymtracka.data.sync.model.requireWorkoutUuid

/**
 * SDK-independent identity/token boundary, without implementation. Android
 * Activity, Google SDK, HTTP, and vault types are constructor concerns for
 * later adapters and never appear in method or model types here.
 *
 * Field mapping follows authentication.md: the service account UUID and
 * nullable display name, the challenge UUID/nonce/expiry, and the grant
 * access/refresh token/expiry fields. Epoch milliseconds map losslessly to
 * the wire RFC3339 timestamps. Client code must never infer the owner from
 * an email address or decoded ID-token contents.
 */

/**
 * An opaque credential value: a Google ID token or a service access/refresh
 * token. The value is never logged, and [toString] is deliberately redacted
 * instead of the autogenerated data-class output.
 */
class OpaqueToken(val value: String) {
    init {
        require(value.isNotEmpty()) { "token value must not be empty" }
    }

    override fun toString(): String = "OpaqueToken(redacted)"

    override fun equals(other: Any?): Boolean = other is OpaqueToken && other.value == value

    override fun hashCode(): Int = value.hashCode()
}

/** Authoritative service account identity; display name is presentation-only. */
data class ServiceAccountRef(
    val accountId: String,
    val displayName: String?,
) {
    init {
        requireWorkoutUuid(accountId, "accountId")
    }
}

/** One-use Google nonce challenge from POST /v1/auth/google/challenge. */
data class ServiceChallenge(
    val challengeId: String,
    val nonce: String,
    val expiresAtMillis: Long,
) {
    init {
        requireWorkoutUuid(challengeId, "challengeId")
        require(nonce.isNotEmpty()) { "challenge nonce must not be empty" }
    }
}

/**
 * Service session grant from exchange/refresh. [toString] is deliberately
 * redacted: it carries the account identity but never token values.
 */
data class ServiceSession(
    val account: ServiceAccountRef,
    val accessToken: OpaqueToken,
    val accessExpiresAtMillis: Long,
    val refreshToken: OpaqueToken,
    val refreshExpiresAtMillis: Long,
) {
    override fun toString(): String =
        "ServiceSession(accountId=${account.accountId}, " +
            "accessExpiresAtMillis=$accessExpiresAtMillis, " +
            "refreshExpiresAtMillis=$refreshExpiresAtMillis)"
}

/**
 * Foreground identity provider. Obtains an opaque Google identity credential
 * for a supplied server nonce and can clear credential state. No interactive
 * credential UI may run from a worker; that restriction belongs to the later
 * Android adapter.
 */
interface GoogleIdentityProvider {
    suspend fun credentialFor(nonce: String): OpaqueToken

    suspend fun clearCredentialState()
}

/**
 * Service authentication API: the four documented challenge, exchange,
 * refresh, and logout operations. Exchange and refresh take an explicit
 * caller-supplied stable idempotency key so lost-response retries replay
 * the original grant instead of minting a second one; refresh must never
 * change the account identity. An expired, revoked, or otherwise invalid
 * refresh credential fails with `reauthentication_required` and requires
 * foreground reauthentication without deleting local domain data. Logout
 * revokes the refresh-token session and is idempotent for an already-revoked
 * token; local sign-out itself always succeeds offline and is handled outside
 * this interface.
 */
interface ServiceAuthApi {
    suspend fun challenge(): ServiceChallenge

    suspend fun exchange(idempotencyKey: String, challengeId: String, idToken: OpaqueToken): ServiceSession

    suspend fun refresh(idempotencyKey: String, refreshToken: OpaqueToken): ServiceSession

    suspend fun logout(refreshToken: OpaqueToken)
}

/**
 * Account/session-bound provider of the opaque service bearer credential.
 * Access denial permits one serialized refresh-and-unchanged-retry; an
 * explicit `reauthentication_required` requires foreground reauthentication
 * instead of another automatic refresh. Neither authorizes account or cache
 * deletion.
 */
interface AccessTokenProvider {
    suspend fun accessToken(): OpaqueToken
}
